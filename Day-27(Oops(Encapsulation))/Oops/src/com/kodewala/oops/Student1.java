package com.kodewala.oops;

public class Student1 {
	private String name;
	private int age;
	private double marks;
	public String getName() {
		return name;
	}
	public void newName(String name) {
		this.name = name;
	}
	public int getAge() {
		return age;
	}
	public void currentAge(int age) {
		this.age = age;
	}
	public double getMarks() {
		return marks;
	}
	public void totalMarks(double marks) {
		this.marks = marks;
	}

}
